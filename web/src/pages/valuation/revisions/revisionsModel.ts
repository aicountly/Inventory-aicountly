export const TIMELINE_PERIODS = [
  { value: '10', label: 'Last 10 days' },
  { value: '30', label: 'Last 30 days' },
  { value: '90', label: 'Last 90 days' },
] as const

export interface TimelineColumns {
  categories: string[]
  increased: number[]
  decreased: number[]
  /** True when the window has no revisions at all. */
  empty: boolean
  /** True when the window was longer than the chart will draw, and says so. */
  truncated: boolean
}

/**
 * The timeline, with the quiet days put back.
 *
 * The API only returns days that have revisions, and a bar chart drawn straight from that
 * would space five scattered days evenly and read as five consecutive ones. The window is
 * filled in here so a gap in the data is a gap on the axis.
 */
export function timelineColumns(summary: RevisionSummary | null, maxDays = 90): TimelineColumns {
  const nothing = { categories: [], increased: [], decreased: [], empty: true, truncated: false }
  if (!summary) return nothing
  const byDay = new Map(summary.timeline.map((p) => [p.day, p]))
  const start = new Date(`${summary.window.from}T00:00:00`)
  const end = new Date(`${summary.window.to}T00:00:00`)
  if (Number.isNaN(start.getTime()) || Number.isNaN(end.getTime())) return nothing
  const categories: string[] = []
  const increased: number[] = []
  const decreased: number[] = []
  const cursor = new Date(start)
  let guard = 0
  while (cursor <= end && guard < maxDays) {
    const pad = (n: number) => String(n).padStart(2, '0')
    const iso = `${cursor.getFullYear()}-${pad(cursor.getMonth() + 1)}-${pad(cursor.getDate())}`
    const point = byDay.get(iso)
    categories.push(cursor.toLocaleDateString('en-GB', { day: '2-digit', month: 'short' }))
    increased.push(point?.increased ?? 0)
    decreased.push(point?.decreased ?? 0)
    cursor.setDate(cursor.getDate() + 1)
    guard += 1
  }
  return {
    categories,
    increased,
    decreased,
    empty: increased.every((n) => n === 0) && decreased.every((n) => n === 0),
    // A range longer than the chart draws is stated, never quietly clipped: a column
    // strip that stops halfway through a quarter reads as a quarter that stopped.
    truncated: cursor <= end,
  }
}

export interface SourceSlice {
  key: string
  label: string
  value: number
  netDelta: number
  revisions: number
  share: number
}

/**
 * Movement by the kind of document that caused it.
 *
 * Sliced on the ABSOLUTE delta: a purchase that added ₹50,000 of cost and a return that took
 * ₹50,000 back are both half the work on this screen, and netting them to zero would draw a
 * source that caused a hundred revisions as no slice at all.
 */
export function sourceSlices(summary: RevisionSummary | null, labelFor: (code: string | null) => string): SourceSlice[] {
  if (!summary) return []
  const total = summary.by_source.reduce((sum, s) => sum + Math.abs(s.abs_delta), 0)
  return summary.by_source
    .filter((s) => s.abs_delta > 0)
    .map((s) => ({
      key: s.document_type ?? 'unknown',
      label: labelFor(s.document_type),
      value: s.abs_delta,
      netDelta: s.net_delta,
      revisions: s.revisions,
      share: total > 0 ? (s.abs_delta / total) * 100 : 0,
    }))
}

export interface AckProgress {
  total: number
  acknowledged: number
  pending: number
  percent: number
  state: 'clear' | 'on-track' | 'attention'
  title: string
  detail: string
}

/** Above this many unacknowledged revisions the card stops congratulating anybody. */
export const PENDING_ATTENTION_THRESHOLD = 10

export function ackProgress(summary: RevisionSummary | null): AckProgress | null {
  if (!summary) return null
  const { revisions, acknowledged, pending } = summary.company
  const percent = revisions > 0 ? Math.round((acknowledged / revisions) * 100) : 100
  if (pending === 0) {
    return {
      total: revisions,
      acknowledged,
      pending,
      percent,
      state: 'clear',
      title: 'All caught up',
      detail: 'Every valuation revision has been acknowledged by Books.',
    }
  }
  if (pending >= PENDING_ATTENTION_THRESHOLD) {
    return {
      total: revisions,
      acknowledged,
      pending,
      percent,
      state: 'attention',
      title: 'Action required',
      detail: 'Unacknowledged revisions keep showing up in reconciliation until Books re-posts the COGS.',
    }
  }
  return {
    total: revisions,
    acknowledged,
    pending,
    percent,
    state: 'on-track',
    title: "You're on track",
    detail: 'Keep acknowledging as Books re-posts, and reconciliation stays clean.',
  }
}

