export interface AckSelection {
  eligible: ValuationRevision[]
  /** Already applied in Books — the API would ignore them, so neither do we. */
  ineligible: ValuationRevision[]
  netDelta: number
  absDelta: number
  /** Eligible rows Books has not been handed yet. Acknowledging these is a claim. */
  awaitingPublish: number
}

export function ackSelection(
  rows: readonly ValuationRevision[],
  selected: ReadonlySet<number>,
): AckSelection {
  const eligible: ValuationRevision[] = []
  const ineligible: ValuationRevision[] = []
  let netDelta = 0
  let absDelta = 0
  let awaitingPublish = 0
  for (const row of rows) {
    if (!selected.has(row.revision_id)) continue
    if (row.acknowledged) {
      ineligible.push(row)
      continue
    }
    eligible.push(row)
    const delta = row.delta_amount ?? 0
    netDelta += delta
    absDelta += Math.abs(delta)
    if (!row.published_at) awaitingPublish += 1
  }
  return { eligible, ineligible, netDelta, absDelta, awaitingPublish }
}

