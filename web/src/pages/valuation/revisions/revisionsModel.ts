/**
 * What "high impact" means, in base currency.
 *
 * A fixed, stated figure rather than a percentile of whatever happens to be on screen: a chip
 * whose meaning moves with the data cannot be compared between two days, and the operator can
 * type any other threshold into the field beside it.
 */
export const HIGH_IMPACT_THRESHOLD = 10000

export interface QuickFilter {
  key: string
  label: string
  title: string
  patch: Record<string, string>
}

/** Monday of the week `now` falls in, ISO. */
export function weekStart(now: Date): string {
  const d = new Date(now.getFullYear(), now.getMonth(), now.getDate())
  const shift = (d.getDay() + 6) % 7
  d.setDate(d.getDate() - shift)
  const pad = (n: number) => String(n).padStart(2, '0')
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`
}

export function isoDate(now: Date): string {
  const pad = (n: number) => String(n).padStart(2, '0')
  return `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())}`
}

