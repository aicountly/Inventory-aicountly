/**
 * What the engine recorded as the reason it re-costed. These are the only "why" this screen
 * can state, because they are the trigger the job was queued with — not a guess made from
 * the shape of the numbers.
 */
export const TRIGGER_LABELS: Record<string, string> = {
  backdated_document: 'Back-dated document postings',
  reversal: 'Document reversals',
  revaluation: 'Stock revaluations',
  method_change: 'A valuation method change',
  manual: 'Manually queued recalculations',
  migration_rebuild: 'A migration rebuild',
}

export function triggerLabel(kind: string | null | undefined): string {
  if (!kind) return 'Recalculations with no recorded trigger'
  return TRIGGER_LABELS[kind] ?? humanize(kind)
}

/**
 * An item whose rate moved far further this time than it usually does.
 *
 * Deliberately conservative, because an "anomaly" a reader chases and finds nothing behind
 * costs more than one the screen kept quiet about:
 *
 *  - the item needs a real baseline (at least `minSamples` revisions in the window), so a
 *    first-ever revision is never an anomaly;
 *  - the move has to be at least `minChangePct`, so a 0.3% drift against a 0.1% average does
 *    not qualify on the ratio alone;
 *  - and it has to be at least `multiple` times that baseline.
 */
export function findAnomalies(
  summary: RevisionSummary | null,
  { minSamples = 3, minChangePct = 10, multiple = 2 } = {},
): RevisionItemSplit[] {
  if (!summary) return []
  return summary.top_items
    .filter((item) => {
      const peak = item.peak_change_pct
      const baseline = item.baseline_pct
      if (peak === null || baseline === null) return false
      if (item.baseline_samples < minSamples) return false
      if (peak < minChangePct) return false
      return baseline > 0 && peak >= baseline * multiple
    })
    .sort((a, b) => (b.peak_change_pct ?? 0) - (a.peak_change_pct ?? 0))
}

export interface RevisionInsight {
  key: string
  kind: 'driver' | 'anomaly' | 'contributor' | 'backlog'
  /** The claim's strength, shown as the block's eyebrow. */
  label: string
  title: string
  /** In base currency, when the insight is about money. */
  amount?: number
  percent?: number
  detail: string
  tone: Tone
  link?: { to: string; label: string }
}

/**
 * The insight panel's contents.
 *
 * Every line is arithmetic over figures the API returned, and it is worded as what it is: a
 * share, a comparison against a stated baseline, a count of jobs by their recorded trigger.
 * Nothing here says "because" — "Possible contributor" is the strongest claim available,
 * because correlation between a trigger and a delta is all the data supports.
 */
export function buildInsights(summary: RevisionSummary | null): RevisionInsight[] {
  if (!summary) return []
  const out: RevisionInsight[] = []
  const { filtered, top_items: topItems, triggers, company } = summary

  const driver = topItems[0]
  if (driver && driver.abs_delta > 0) {
    const share = filtered.abs_delta > 0 ? (driver.abs_delta / filtered.abs_delta) * 100 : 0
    out.push({
      key: `driver-${driver.item_id}`,
      kind: 'driver',
      label: 'Top variance driver',
      title: driver.item_sku || driver.item_name || `Item #${driver.item_id}`,
      amount: driver.net_delta,
      percent: share,
      detail: `${share.toFixed(0)}% of the valuation movement in view, across ${driver.revisions} revision${driver.revisions === 1 ? '' : 's'}.`,
      tone: driver.net_delta >= 0 ? 'danger' : 'success',
      link: { to: `/valuation/cost-layers?item_id=${driver.item_id}`, label: 'Open cost layers' },
    })
  }

  const anomaly = findAnomalies(summary)[0]
  if (anomaly) {
    out.push({
      key: `anomaly-${anomaly.item_id}`,
      kind: 'anomaly',
      label: 'Unusual rate change',
      title: anomaly.item_sku || anomaly.item_name || `Item #${anomaly.item_id}`,
      percent: anomaly.peak_change_pct ?? undefined,
      detail: `Rate moved ${(anomaly.peak_change_pct ?? 0).toFixed(0)}% against a ${(anomaly.baseline_pct ?? 0).toFixed(1)}% average over the last ${summary.baseline_days} days (${anomaly.baseline_samples} revisions).`,
      tone: 'warning',
      link: { to: `/valuation/cost-layers?item_id=${anomaly.item_id}`, label: 'Investigate cost layers' },
    })
  }

  const trigger = dominantTrigger(triggers, filtered.revisions)
  if (trigger) {
    out.push({
      key: `trigger-${trigger.trigger_kind ?? 'none'}`,
      kind: 'contributor',
      label: 'Possible contributor',
      title: triggerLabel(trigger.trigger_kind),
      detail: `${trigger.jobs} recalculation job${trigger.jobs === 1 ? '' : 's'} with this trigger produced ${trigger.revisions} of the ${filtered.revisions} revisions in view.`,
      tone: 'info',
      link: trigger.trigger_kind
        ? { to: `/valuation/recalculations?trigger_kind=${trigger.trigger_kind}`, label: 'See the jobs' }
        : undefined,
    })
  }

  if (company.pending > 0) {
    out.push({
      key: 'backlog',
      kind: 'backlog',
      label: 'Reconciliation exposure',
      title: `${company.pending} awaiting Books`,
      amount: company.pending_delta,
      detail:
        company.awaiting_publish > 0
          ? `${company.awaiting_publish} of them have not been published to Books yet.`
          : 'All of them are with Books, waiting for the COGS to be re-posted.',
      tone: company.pending >= PENDING_ATTENTION_THRESHOLD ? 'danger' : 'warning',
      link: { to: '/reconciliation/posting-status', label: 'Open reconciliation' },
    })
  }

  return out
}

/** The trigger behind at least half the revisions in view, if there is one. */
export function dominantTrigger(
  triggers: readonly RevisionTriggerSplit[],
  totalRevisions: number,
): RevisionTriggerSplit | null {
  if (totalRevisions <= 0) return null
  const top = [...triggers].sort((a, b) => b.revisions - a.revisions)[0]
  if (!top || top.revisions === 0) return null
  return top.revisions / totalRevisions >= 0.5 ? top : null
}

export interface RevisionAction {
  key: string
  label: string
  to: string
}

/**
 * What to do next — every entry a route that exists, gated by the permission that route needs.
 *
 * An action nobody can perform is worse than no suggestion: it sends an operator to a screen
 * that will refuse them.
 */
export function buildActions(
  summary: RevisionSummary | null,
  can: { recalculate: boolean; reconcile: boolean },
): RevisionAction[] {
  if (!summary) return []
  const out: RevisionAction[] = []
  if (summary.company.pending > 0 && can.reconcile) {
    out.push({
      key: 'reconcile',
      label: `Clear ${summary.company.pending} unacknowledged revision${summary.company.pending === 1 ? '' : 's'} in reconciliation`,
      to: '/reconciliation/posting-status',
    })
  }
  const backdated = summary.triggers.find((t) => t.trigger_kind === 'backdated_document')
  if (backdated && backdated.revisions > 0) {
    out.push({
      key: 'backdated',
      label: `Review the ${backdated.jobs} back-dated recalculation${backdated.jobs === 1 ? '' : 's'}`,
      to: '/valuation/recalculations?trigger_kind=backdated_document',
    })
  }
  if (summary.jobs.failed > 0 && can.recalculate) {
    out.push({
      key: 'failed-jobs',
      label: `Investigate ${summary.jobs.failed} failed recalculation job${summary.jobs.failed === 1 ? '' : 's'}`,
      to: '/valuation/recalculations?status=FAILED',
    })
  }
  const anomaly = findAnomalies(summary)[0]
  if (anomaly) {
    out.push({
      key: `layers-${anomaly.item_id}`,
      label: `Check the cost layers of ${anomaly.item_sku || anomaly.item_name || `item #${anomaly.item_id}`}`,
      to: `/valuation/cost-layers?item_id=${anomaly.item_id}`,
    })
  }
  if (summary.jobs.queued + summary.jobs.running > 0 && can.recalculate) {
    out.push({
      key: 'queue',
      label: `Watch ${summary.jobs.queued + summary.jobs.running} job${summary.jobs.queued + summary.jobs.running === 1 ? '' : 's'} still in the queue`,
      to: '/valuation/recalculations?status=QUEUED,RUNNING',
    })
  }
  return out.slice(0, 4)
}
