/**
 * Where a revision has got to between the two products.
 *
 * Inventory generates it (`pending`), publishes it to Books (`published`), and Books
 * acknowledges it once the COGS has been re-posted (`applied`). Three states, not two: only
 * the middle one means "Books has it and has not answered yet", and a screen that merged it
 * with the first would hide a revision that never left Inventory at all — which is the one
 * an operator most needs to find.
 */
export type BooksState = 'pending' | 'published' | 'applied'

export function booksState(r: Pick<ValuationRevision, 'acknowledged' | 'published_at'>): BooksState {
  if (r.acknowledged) return 'applied'
  return r.published_at ? 'published' : 'pending'
}

