export type DeltaDirection = 'increase' | 'decrease' | 'flat'

export function deltaDirection(delta: number | null | undefined): DeltaDirection {
  const n = typeof delta === 'number' && Number.isFinite(delta) ? delta : 0
  if (n > 0) return 'increase'
  if (n < 0) return 'decrease'
  return 'flat'
}

/**
 * What the sign of a valuation delta means, and how it is said out loud.
 *
 * A positive delta is stock that now costs MORE than the books thought it did: margin
 * pressure and a COGS increase to re-post. It is drawn in the warning colour for that reason,
 * not because "negative is red" — on a costing screen that instinct is backwards.
 *
 * `srLabel` exists because the colour is a hint, never the message: it is read out with the
 * figure, so the meaning survives a monochrome print, a colour-blind reader and a screen
 * reader alike.
 */
export const DELTA_MEANING: Record<DeltaDirection, { tone: Tone; srLabel: string }> = {
  increase: { tone: 'danger', srLabel: 'cost increase' },
  decrease: { tone: 'success', srLabel: 'cost decrease' },
  flat: { tone: 'neutral', srLabel: 'no change' },
}

export const DELTA_FILTER_OPTIONS = [
  { value: '', label: 'Any movement' },
  { value: 'increase', label: 'Cost increased' },
  { value: 'decrease', label: 'Cost decreased' },
  { value: 'none', label: 'No change' },
] as const

