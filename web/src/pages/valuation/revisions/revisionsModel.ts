/**
 * Everything the valuation-revisions screen decides, as pure functions.
 *
 * The screen itself only renders: which Books state a row is in, whether a delta is cost
 * pressure or relief, what the insight panel is allowed to claim and which of those claims
 * has a real route behind it all live here, where they can be unit tested. A rule that lives
 * in JSX is a rule nobody can check.
 */

