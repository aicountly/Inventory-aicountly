/** Matches the list's own default: work to do first. */
export const DEFAULT_BOOKS_FILTER = 'unacknowledged'

/**
 * The `books` filter as the API's two parameters.
 *
 * `acknowledged` is sent alongside `books` on purpose. It is the parameter this endpoint has
 * always had, so an API deployed before this screen was rebuilt still narrows the list to the
 * right side of the acknowledgement line instead of silently ignoring the filter and showing
 * applied revisions under a heading that says "Awaiting Books".
 */
export function booksFilterQuery(books: string): { books?: string; acknowledged?: string } {
  switch (books) {
    case 'unacknowledged':
      return { books: 'unacknowledged', acknowledged: '0' }
    case 'pending':
      return { books: 'awaiting', acknowledged: '0' }
    case 'published':
      return { books: 'published', acknowledged: '0' }
    case 'acknowledged':
      return { books: 'acknowledged', acknowledged: '1' }
    default:
      // 'all' — and anything unrecognised, which must never narrow silently.
      return {}
  }
}

